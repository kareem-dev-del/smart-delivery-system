type LocaleContextValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (message: string) => string };
const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    try {
      return window.localStorage.getItem("smartdrop-admin-locale") === "ar" ? "ar" : "en";
    } catch {
      return "en";
    }
  });

  const setLocale = (next: Locale) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem("smartdrop-admin-locale", next);
    } catch {
      // Keep the in-memory preference when storage is unavailable.
    }
  };

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    document.documentElement.dataset.locale = locale;
  }, [locale]);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    setLocale,
    t: (message) => locale === "ar" ? (messages[message] ?? message) : message,
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useLocale must be used within LocaleProvider");
  return context;
}
